#!/bin/bash -l
#SBATCH -J g05_smoke
#SBATCH -o /export/home/kaziz/g05/logs/slurm-%x-%j.out
#SBATCH -A h200
#SBATCH --qos h200_qos
#SBATCH -p gpu-H200
#SBATCH --gres gpu:1
#SBATCH -c 16
#SBATCH --mem 128000MB
#SBATCH --time 04:00:00
# Phase 0 gates: GPU/driver, stack imports, merged-data config + stats, 2-step FM training smoke, release eval smoke.
source /export/home/kaziz/g05/env_g05.sh
cd $PROJECT_ROOT
declare -A RC
run() { local n=$1; shift; echo; echo ">>> [$n] $(date +%T)"; "$@"; RC[$n]=$?; echo "<<< [$n] rc=${RC[$n]} $(date +%T)"; }

run gpu nvidia-smi --query-gpu=name,driver_version,memory.total --format=csv
run libero $PY -c "from libero.libero import benchmark; print('libero ok', len(benchmark.get_benchmark_dict()), 'benchmarks')"
run lawam_import $PY -c "import sys; sys.path.insert(0, '$LAWAM_ROOT'); import latent_action_model.core.lam_model; print('lawam lam_model ok')"
run stack $PY -c "
import torch, fla
print('torch', torch.__version__, 'cuda', torch.version.cuda, 'avail', torch.cuda.is_available(), torch.cuda.get_device_name(0))
x = torch.randn(256, 256, device='cuda', dtype=torch.bfloat16); print('bf16 matmul ok', (x @ x).float().abs().mean().item())
"

# Data config for LaWAM's merged LeRobot v3.0 set (256x256, one dir). Released g05-libero used 4 dirs @512.
run data_cfg $PY - <<'PYEOF'
import yaml, copy
src = yaml.safe_load(open('configs/data/libero.yaml'))
cfg = copy.deepcopy(src)
def fix_images(shape_meta):
    for im in shape_meta.get('images', []):
        im['raw_shape'] = [3, 256, 256]
for name, ds in cfg['embodiment_datasets'].items():
    fix_images(ds['shape_meta'])
    for g in ds['dataset_groups']:
        g['dataset_dirs'] = ['data/libero/libero_merged_no_noops']
for name, p in cfg.get('processors', {}).items():
    if 'shape_meta' in p: fix_images(p['shape_meta'])
open('configs/data/libero_merged.yaml', 'w').write('# Generated by g05 jobs/02_smoke.sh from libero.yaml: merged 4-suite dir, 256x256 sources.\n' + yaml.safe_dump(cfg, sort_keys=False))
print(open('configs/data/libero_merged.yaml').read()[:1500])
PYEOF
run inspect_data $PY -c "
import json; m=json.load(open('data/libero/libero_merged_no_noops/meta/info.json'))
print({k:m[k] for k in ['codebase_version','fps','total_episodes','total_frames']})
for k,v in m['features'].items(): print(' ', k, v.get('dtype'), v.get('shape'), (v.get('info') or {}).get('video.codec',''))
"
run stats $PY tests/test_dataloader_batch.py --mixture configs/data/libero_merged.yaml --stats data/stats/libero_merged_stats.json --stats-downsample-rate 1

run train_smoke bash scripts/run/finetune.sh 1 libero --test --dataset libero_merged \
    datastatics_path=data/stats/libero_merged_stats.json model.max_steps=2 model.num_workers=2
grep -hE 'Loaded|Missing|rand init|LOSSLESS|Loss:|Max step|pixel_values' runs/libero/test/*/*.log 2>/dev/null | tail -40

run eval_smoke env TORCH_FORCE_NO_WEIGHTS_ONLY_LOAD=1 HF_HUB_OFFLINE=1 TRANSFORMERS_OFFLINE=1 bash scripts/run/eval_libero.sh checkpoints/g05-libero/model.pt \
    --suites "libero_goal" --num_trials 1 --num_parallel 2 --output_dir $G05_ROOT/results/smoke_release_goal
[ -f $G05_ROOT/results/smoke_release_goal/summary.json ] && cat $G05_ROOT/results/smoke_release_goal/summary.json | head -40
grep -hE 'step|s/ep|elapsed|time' $G05_ROOT/results/smoke_release_goal/libero_goal/client.log 2>/dev/null | tail -5

echo; echo "== summary"; FAIL=0; for k in gpu libero lawam_import stack data_cfg inspect_data stats train_smoke eval_smoke; do echo "$k rc=${RC[$k]}"; [[ ${RC[$k]} != 0 ]] && FAIL=1; done
exit $FAIL
